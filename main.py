def persist_report(report_data: dict, conn=None):
    """Inserts or updates an OIML report inside SQLite."""
    local_conn = conn or get_db_connection()
    cursor = local_conn.cursor()
    inst = report_data.get("instrument", {})

    cursor.execute("""
    INSERT OR REPLACE INTO reports (
        id, created_at, serial_number, manufacturer, model,
        accuracy_class, max_capacity, scale_interval_e,
        overall_verdict, verification_hash, full_json
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
    """, (
        report_data.get("id"),
        report_data.get("createdAt", datetime.utcnow().isoformat() + "Z"),
        inst.get("serialNumber", "UNKNOWN"),
        inst.get("manufacturer", "Generic"),
        inst.get("model", "Standard"),
        inst.get("accuracyClass", "CLASS_III"),
        float(inst.get("maxCapacity", 30.0)),
        float(inst.get("scaleIntervalE", 0.005)),
        report_data.get("overallVerdict", "PENDING"),
        report_data.get("verificationHash", ""),
        json.dumps(report_data)
    ))

    if not conn:
        local_conn.commit()
        local_conn.close()

def calculate_mpe(load_val: float, accuracy_class: str, e: float, is_in_service: bool = False) -> float:
    """
    Computes Maximum Permissible Error (MPE) as prescribed by OIML R-76 Table 6.
    Class I, II, III, and IV limits based on verification scale intervals (m = m/e).
    """
    if e <= 0:
        return 0.0

    m = abs(load_val) / e
    factor = 0.5
    acc = str(accuracy_class).upper()

    if "I" in acc and "II" not in acc and "IV" not in acc:  # Special Accuracy Class I
        if m <= 50000:
            factor = 0.5
        elif m <= 200000:
            factor = 1.0
        else:
            factor = 1.5
    elif "II" in acc and "III" not in acc:  # High Accuracy Class II
        if m <= 5000:
            factor = 0.5
        elif m <= 20000:
            factor = 1.0
        else:
            factor = 1.5
    elif "IV" in acc:  # Ordinary Accuracy Class IV
        if m <= 50:
            factor = 0.5
        elif m <= 200:
            factor = 1.0
        else:
            factor = 1.5
    else:  # Medium Accuracy Class III (Commercial & Industrial Standard)
        if m <= 500:
            factor = 0.5
        elif m <= 2000:
            factor = 1.0
        else:
            factor = 1.5

    # In-service verification tolerance is double the initial verification tolerance
    multiplier = 2.0 if is_in_service else 1.0
    return round(factor * e * multiplier, 6)

def evaluate_oiml_report(report: dict) -> dict:
    """
    Deterministic evaluation of:
    1. Weighing Performance & Hysteresis
    2. Eccentricity (Corner Load)
    3. Repeatability (Reproducibility & Variance)
    """
    specs = report.get("instrument", {})
    e = float(specs.get("scaleIntervalE", 0.005))
    acc_class = specs.get("accuracyClass", "CLASS_III")
    is_in_service = report.get("verificationType") == "in_service"

    # 1. Weighing Test
    weighing_points = report.get("weighingTest", [])
    weighing_passed = True
    for p in weighing_points:
        load = float(p.get("nominalLoad", 0.0))
        mpe = calculate_mpe(load, acc_class, e, is_in_service)
        p["mpe"] = mpe

        inc = float(p.get("indicatedIncreasing", load))
        dec = float(p.get("indicatedDecreasing", load))
        err_inc = round(inc - load, 6)
        err_dec = round(dec - load, 6)

        p["errorIncreasing"] = err_inc
        p["errorDecreasing"] = err_dec
        p["hysteresis"] = round(abs(inc - dec), 6)
        p["passIncreasing"] = abs(err_inc) <= (mpe + 1e-9)
        p["passDecreasing"] = abs(err_dec) <= (mpe + 1e-9)
        p["passOverall"] = p["passIncreasing"] and p["passDecreasing"]

        if not p["passOverall"]:
            weighing_passed = False

    # 2. Eccentricity Test (Corner Loading)
    ecc_points = report.get("eccentricityTest", [])
    ecc_passed = True
    readings = []
    for c in ecc_points:
        load = float(c.get("appliedLoad", float(specs.get("maxCapacity", 30)) / 3))
        mpe = calculate_mpe(load, acc_class, e, is_in_service)
        c["mpe"] = mpe
        ind = float(c.get("indicatedValue", load))
        readings.append(ind)
        err = round(ind - load, 6)
        c["error"] = err
        c["pass"] = abs(err) <= (mpe + 1e-9)

        if not c["pass"]:
            ecc_passed = False

    max_diff = round(max(readings) - min(readings), 6) if readings else 0.0

    # 3. Repeatability Test
    rep = report.get("repeatabilityTest", {})
    runs = rep.get("runs", [])
    rep_passed = True
    rep_values = [float(r.get("indicatedValue", 0.0)) for r in runs if "indicatedValue" in r]

    if rep_values:
        rep_load = float(rep.get("appliedLoad", float(specs.get("maxCapacity", 30)) * 0.5))
        mpe_rep = calculate_mpe(rep_load, acc_class, e, is_in_service)
        rep["mpe"] = mpe_rep
        range_diff = round(max(rep_values) - min(rep_values), 6)
        rep["rangeDifference"] = range_diff
        rep["maxReading"] = max(rep_values)
        rep["minReading"] = min(rep_values)
        mean_val = sum(rep_values) / len(rep_values)
        variance = sum((x - mean_val) ** 2 for x in rep_values) / len(rep_values)
        rep["stdDev"] = round(math.sqrt(variance), 6)
        rep_passed = range_diff <= (mpe_rep + 1e-9)
        rep["pass"] = rep_passed

    overall_verdict = "PASS" if (weighing_passed and ecc_passed and rep_passed) else "FAIL"
    clean_id = "".join(filter(str.isalnum, str(report.get("id", "REPORT"))))
    v_hash = (
        f"SHA256-OIML76-CERTIFIED-{clean_id}"
        if overall_verdict == "PASS"
        else f"SHA256-FAIL-NONCONFORMING-{clean_id}"
    )

    report.update({
        "weighingTestPassed": weighing_passed,
        "eccentricityTestPassed": ecc_passed,
        "eccentricityMaxDiff": max_diff,
        "repeatabilityTestPassed": rep_passed,
        "overallVerdict": overall_verdict,
        "verificationHash": v_hash,
    })
    return report

