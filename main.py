@app.get("/api/reports")
def list_reports():
    """Retrieves all verification records from the SQLite database."""
    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT full_json FROM reports ORDER BY created_at DESC")
    rows = cursor.fetchall()
    conn.close()
    return [json.loads(r["full_json"]) for r in rows]

@app.get("/api/reports/{report_id}")
def get_report(report_id: str):
    """Retrieves a specific test report by unique identifier."""
    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute("SELECT full_json FROM reports WHERE id = ?", (report_id,))
    row = cursor.fetchone()
    conn.close()

    if not row:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Report '{report_id}' was not found in the SQLite register.",
        )
    return json.loads(row["full_json"])

@app.post("/api/reports")
def create_or_update_report(report: dict):
    """
    Evaluates raw test measurements against OIML R-76 MPE limits
    and immediately persists the computed results into SQLite.
    """
    rep_id = report.get("id")
    if not rep_id:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Attribute 'id' is required for verification reports.",
        )

    evaluated = evaluate_oiml_report(report)
    persist_report(evaluated)
    return evaluated

@app.post("/api/reports/reset")
def reset_to_benchmark_seeds():
    """Resets the SQLite repository back to initial benchmark records."""
    conn = get_db_connection()
    cursor = conn.cursor()
    cursor.execute("DELETE FROM reports")
    conn.commit()

    for benchmark in BENCHMARK_REPORTS:
        evaluated = evaluate_oiml_report(benchmark)
        persist_report(evaluated, conn)

    cursor.execute("SELECT full_json FROM reports ORDER BY created_at DESC")
    rows = cursor.fetchall()
    conn.close()
    return [json.loads(r["full_json"]) for r in rows]

