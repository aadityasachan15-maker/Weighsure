@app.post("/api/gemini/explain")
def explain_diagnosis(req: ExplainRequest):
    """Metrology diagnostic assistant providing technical analysis in clear English."""
    report = req.reportData
    is_pass = report.get("overallVerdict") == "PASS"
    inst = report.get("instrument", {})
    unit = inst.get("unit", "kg")

    failed_corners = [c for c in report.get("eccentricityTest", []) if not c.get("pass", True)]
    failed_weighing = [w for w in report.get("weighingTest", []) if not w.get("passOverall", True)]
    rep_failed = not report.get("repeatabilityTestPassed", True)

    if is_pass:
        text = (
            f"**OIML R-76 Technical Verification: CONFORMING (PASS)**\n\n"
            f"The non-automatic weighing instrument **{inst.get('manufacturer')} {inst.get('model')}** "
            f"(Accuracy Class: {inst.get('accuracyClass')}, Max: {inst.get('maxCapacity')} {unit}, e: {inst.get('scaleIntervalE')} {unit}) "
            f"conforms to statutory verification limits under OIML Recommendation R-76.\n\n"
            f"• **Weighing Accuracy**: All measured loading and unloading points are strictly within MPE tolerances.\n"
            f"• **Eccentricity (Corner Load)**: Platter loading points show acceptable deviation across quadrants.\n"
            f"• **Repeatability**: Repeated test cycles demonstrate standard deviation below statutory limit.\n\n"
            f"**Conclusion**: The instrument satisfies statutory criteria. Physical stamping and certification are approved."
        )
    else:
        text = (
            f"**OIML R-76 Non-Conformance Diagnosis: REJECTED (FAIL)**\n\n"
            f"The instrument **{inst.get('manufacturer')} {inst.get('model')}** failed statutory tolerances:\n\n"
        )
        if failed_corners:
            corner_names = ", ".join([c.get("position", "") for c in failed_corners])
            text += f"• **Corner Eccentricity Failure**: Significant shift detected at {corner_names} exceeding MPE.\n"
        if failed_weighing:
            text += "• **Weighing Accuracy Failure**: High-capacity loading errors exceeded the permissible envelope.\n"
        if rep_failed:
            text += "• **Repeatability Failure**: Variance across identical test cycles exceeded allowable limits.\n"
        text += (
            "\n**Corrective Engineering Steps**:\n"
            "1. Inspect platter seating and clear debris from mechanical overload stops.\n"
            "2. Verify base leveling using the spirit level bubble.\n"
            "3. Trim the load cell summing junction potentiometers for corner balance.\n"
            "4. Perform span calibration using calibrated Class F or M1 reference standards."
        )

    return {
        "text": text,
        "source": "deterministic_python_sqlite_engine",
    }

